"""BERHOT-owned, deterministic TRAIN-ONLY byte BPE. No pretrained vocabulary.

The first 256 symbols represent literal UTF-8 bytes; merges are fitted only
from the frozen TRAIN shard. Source-text round trips are exact, including
Arabic and characters unseen in training. Generated byte sequences may need
Unicode replacement decoding; this is not a fluency guarantee.
"""
from collections import Counter
import hashlib
import json


FORMAT = "berhot_train_only_byte_bpe_v1"


def canonical_bytes(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True,
                      separators=(",", ":")).encode("utf-8")


def digest(value):
    return hashlib.sha256(canonical_bytes(value)).hexdigest()


def _merge(ids, a, b, new_id):
    output = []
    i = 0
    while i < len(ids):
        if i + 1 < len(ids) and ids[i] == a and ids[i + 1] == b:
            output.append(new_id)
            i += 2
        else:
            output.append(ids[i])
            i += 1
    return output


def fit_byte_bpe(train_bytes, vocab_size=320, sample_bytes=120000):
    if not isinstance(train_bytes, bytes) or not train_bytes:
        raise ValueError("Nonempty TRAIN bytes required")
    train_bytes.decode("utf-8", errors="strict")
    if not 256 <= int(vocab_size) <= 1024:
        raise ValueError("vocab_size must be 256..1024")
    if not 2048 <= int(sample_bytes) <= 2000000:
        raise ValueError("sample_bytes must be 2048..2000000")
    tokens = list(train_bytes[:int(sample_bytes)])
    merges = []
    while len(merges) + 256 < int(vocab_size):
        pairs = Counter(zip(tokens, tokens[1:]))
        if not pairs:
            break
        a, b = min(pairs, key=lambda pair: (-pairs[pair], pair))
        if pairs[(a, b)] < 2:
            break
        next_id = 256 + len(merges)
        merges.append([a, b])
        tokens = _merge(tokens, a, b, next_id)
    return {
        "format": FORMAT,
        "base_bytes": 256,
        "vocab_size": 256 + len(merges),
        "requested_vocab_size": int(vocab_size),
        "sample_bytes": min(len(train_bytes), int(sample_bytes)),
        "train_sha256": hashlib.sha256(train_bytes).hexdigest(),
        "merges": merges,
    }


def validate_bpe(tokenizer):
    if not isinstance(tokenizer, dict) or tokenizer.get("format") != FORMAT:
        raise ValueError("Unsupported byte BPE tokenizer format")
    merges = tokenizer.get("merges")
    if not isinstance(merges, list) or not (
        256 <= tokenizer.get("vocab_size", 0) <= 1024
        and tokenizer["vocab_size"] == 256 + len(merges)
    ):
        raise ValueError("Invalid byte BPE vocabulary")
    for i, pair in enumerate(merges):
        if (not isinstance(pair, list) or len(pair) != 2 or
            any(type(x) is not int or x < 0 or x >= 256 + i for x in pair)):
            raise ValueError("Invalid or forward-referencing byte BPE merge")
    if tokenizer.get("base_bytes") != 256:
        raise ValueError("Invalid byte alphabet")
    return tokenizer


def encode_bpe(data, tokenizer):
    validate_bpe(tokenizer)
    if not isinstance(data, bytes):
        raise TypeError("encode_bpe expects bytes")
    ids = list(data)
    for rank, (a, b) in enumerate(tokenizer["merges"]):
        ids = _merge(ids, a, b, rank + 256)
    return ids


def token_bytes(tokenizer):
    validate_bpe(tokenizer)
    vocabulary = [bytes([i]) for i in range(256)]
    for a, b in tokenizer["merges"]:
        vocabulary.append(vocabulary[a] + vocabulary[b])
    return vocabulary


def decode_bpe(ids, tokenizer):
    vocabulary = token_bytes(tokenizer)
    if any(type(i) is not int or i < 0 or i >= len(vocabulary) for i in ids):
        raise ValueError("Out of range byte BPE token")
    return b"".join(vocabulary[i] for i in ids)
